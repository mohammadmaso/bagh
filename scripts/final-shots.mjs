import { chromium } from '@playwright/test'
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } })
const logs = []
page.on('console', (m) => { if (['error', 'warning'].includes(m.type())) logs.push(m.text()) })
page.on('pageerror', (e) => logs.push('PAGEERROR ' + e.message))
await page.goto((process.env.URL ?? 'http://localhost:4173/') + '?q=medium')
await page.waitForFunction(() => window.__engine && window.__garden)
await page.evaluate(() => window.__garden.store.getState().setUI({ tourDone: true, showRules: false }))
await page.evaluate(() => window.__garden.loadExample())
const set = (t) => page.evaluate((t) => window.__garden.store.getState().setTime(t), t)
const shot = async (n, wait = 5000) => { await page.waitForTimeout(wait); await page.screenshot({ path: `docs/screenshots/${n}.png`, timeout: 240000 }) }
const cam = (p, t) => page.evaluate(([p, t]) => { const e = window.__engine; e.camera.position.set(...p); e.controls.target.set(...t); e.controls.update() }, [p, t])
await cam([-9, 10.5, 36], [16.5, 2.2, 15])
await set({ month: 6, day: 21, minutes: 7 * 60 + 30, ageYears: 8, seasonMode: 'auto', snow: false }); await shot('persp-morning', 9000)
await set({ minutes: 12 * 60 + 30 }); await shot('persp-noon')
await set({ minutes: 18 * 60 + 40 }); await shot('persp-evening')
await set({ month: 1, day: 10, minutes: 12 * 60, ageYears: 8 }); await shot('persp-winter')
await set({ snow: true }); await shot('persp-snow')
await set({ month: 4, day: 8, minutes: 11 * 60, snow: false }); await shot('persp-spring')
await set({ month: 6, day: 21, minutes: 12 * 60 + 30, ageYears: 0 }); await shot('age-0')
await set({ ageYears: 15 }); await shot('age-15')
await page.evaluate(() => window.__garden.store.getState().setUI({ view: 'plan' })); await shot('plan')
await page.evaluate(() => window.__garden.store.getState().setUI({ view: 'persp' }))
await page.evaluate(() => { [...document.querySelectorAll('[role=tab]')].find((b) => b.textContent.startsWith('Analysis')).click() }); await page.waitForTimeout(500); await page.evaluate(() => { [...document.querySelectorAll('button')].find((b) => b.textContent === 'Run analysis').click() })
await page.waitForFunction(() => window.__garden.analysis.getState().sun.status === 'done', null, { timeout: 280000 })
await shot('sun-heatmap', 6000)
await page.evaluate(() => window.__garden.store.getState().setUI({ overlay: 'none', view: 'walk' })); await shot('walk')
console.log(logs.slice(0, 10).join('\n'))
await browser.close()
