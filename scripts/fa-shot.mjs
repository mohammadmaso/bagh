import { chromium } from '@playwright/test'
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } })
const logs = []
page.on('console', (m) => { if (!['debug', 'info', 'log'].includes(m.type())) logs.push(m.type() + ': ' + m.text()) })
page.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message))
await page.goto((process.env.URL ?? 'http://localhost:4173/') + '?q=medium')
await page.waitForFunction(() => window.__engine && window.__garden)
await page.evaluate(() => { window.__garden.store.getState().setUI({ tourDone: true }) })
await page.getByRole('button', { name: /File/ }).click()
await page.getByRole('menuitem', { name: /Load example layout/ }).click()
await page.waitForTimeout(1500)
await page.getByRole('button', { name: 'Language' }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: 'shots/fa_main.png' })
await page.getByRole('tab', { name: 'قوانین' }).click()
await page.waitForTimeout(2500)
await page.screenshot({ path: 'shots/fa_rules.png' })
console.log(await page.evaluate(() => JSON.stringify({ dir: document.documentElement.dir, lang: document.documentElement.lang })))
console.log(logs.slice(0, 20).join('\n'))
await browser.close()
